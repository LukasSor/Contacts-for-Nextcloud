    fun normalize(code: String): String =
        code.trim().lowercase().replace('_', '-')

    fun match(code: String): ContactFieldOptions.Option? {
        val normalized = normalize(code)
        if (normalized.isEmpty()) return all.firstOrNull { it.id.isEmpty() }
        all.firstOrNull { it.id.equals(normalized, ignoreCase = true) }?.let { return it }
        // Web greedyMatch: fr-ca-xxx → fr when only the base tag is listed.
        val base = normalized.substringBefore('-')
        if (base.isNotEmpty() && base != normalized) {
            all.firstOrNull { it.id.equals(base, ignoreCase = true) }?.let { return it }
        }
        return null
    }

    fun label(code: String, locale: java.util.Locale = java.util.Locale.getDefault()): String {
        val matched = match(code)
        val fallback = matched?.label ?: code.trim().ifBlank { "—" }
        if (matched == null || matched.id.isEmpty()) return fallback
        if (locale.language.equals("en", ignoreCase = true)) return matched.label
        val tag = toBcp47(matched.id)
        val display = runCatching { java.util.Locale.forLanguageTag(tag).getDisplayName(locale) }
            .getOrNull()
            ?.trim()
            .orEmpty()
        if (display.isEmpty() ||
            display.equals(tag, ignoreCase = true) ||
            display.equals(matched.id, ignoreCase = true)
        ) {
            return matched.label
        }
        return display
    }

    private fun toBcp47(id: String): String =
        id.split('-').mapIndexed { index, part ->
            when {
                index == 0 -> part.lowercase()
                part.length == 4 -> part.lowercase().replaceFirstChar { it.titlecase() }
                part.length == 2 && part.all { it.isLetter() } -> part.uppercase()
                else -> part
            }
        }.joinToString("-")
